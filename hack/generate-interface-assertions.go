// generate-interface-assertions emits compile-time assertions that every
// generated managed type satisfies resource.Managed and its scope's managed
// interface, one file per API package:
//
//	apis/<scope>/.../zz_generated.interfaces_test.go
//
// A package is an MR package iff it holds an angryjet-generated
// zz_generated.managed.go. Every type that file gives a SetConditions method is
// asserted as resource.Managed, plus resource.LegacyManaged under apis/cluster/
// or resource.ModernManaged under apis/namespaced/.
//
// Run from the provider root, after the step that writes
// zz_generated.managed.go (angryjet, `go generate`):
//
//	go run hack/generate-interface-assertions.go
//
// The emitter takes no module path and imports only the standard library, so
// the file is identical in every provider. Output is committed, so
// `make check-diff` validates it. A zz_generated.interfaces_test.go whose
// package no longer has a zz_generated.managed.go is removed.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	managedFile = "zz_generated.managed.go"
	outputFile  = "zz_generated.interfaces_test.go"
)

func main() {
	if _, err := os.Stat("apis"); err != nil {
		log.Fatalf("generate-interface-assertions: no apis/ — run from the provider root: %v", err)
	}

	managedDirs := map[string]bool{}
	var staleOutputs []string
	err := filepath.WalkDir("apis", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		switch d.Name() {
		case managedFile:
			managedDirs[filepath.Dir(path)] = true
		case outputFile:
			staleOutputs = append(staleOutputs, path)
		}
		return nil
	})
	if err != nil {
		log.Fatalf("generate-interface-assertions: walking apis/: %v", err)
	}

	dirs := make([]string, 0, len(managedDirs))
	for dir := range managedDirs {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)

	for _, dir := range dirs {
		if err := generate(dir); err != nil {
			log.Fatalf("generate-interface-assertions: %s: %v", dir, err)
		}
		fmt.Printf("generate-interface-assertions: wrote %s\n", filepath.Join(dir, outputFile))
	}

	for _, out := range staleOutputs {
		if managedDirs[filepath.Dir(out)] {
			continue
		}
		if err := os.Remove(out); err != nil {
			log.Fatalf("generate-interface-assertions: removing stale %s: %v", out, err)
		}
		fmt.Printf("generate-interface-assertions: removed stale %s\n", out)
	}
}

// legacyOrModern returns the scope-specific interface for an API package, taken
// from its position under apis/. Any other position is an error: a package that
// is neither cluster- nor namespace-scoped has no defined assertion.
func legacyOrModern(dir string) (iface string, legacy bool, err error) {
	parts := strings.Split(filepath.ToSlash(dir), "/")
	if len(parts) < 2 {
		return "", false, fmt.Errorf("not under apis/<scope>/")
	}
	switch parts[1] {
	case "cluster":
		return "LegacyManaged", true, nil
	case "namespaced":
		return "ModernManaged", false, nil
	}
	return "", false, fmt.Errorf("apis/%s is neither apis/cluster nor apis/namespaced", parts[1])
}

func generate(dir string) error {
	scopeIface, legacy, err := legacyOrModern(dir)
	if err != nil {
		return err
	}

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, filepath.Join(dir, managedFile), nil, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("parsing %s: %w", managedFile, err)
	}

	seen := map[string]bool{}
	for _, decl := range f.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || fn.Name.Name != "SetConditions" || len(fn.Recv.List) != 1 {
			continue
		}
		star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
		if !ok {
			continue
		}
		if id, ok := star.X.(*ast.Ident); ok {
			seen[id.Name] = true
		}
	}
	if len(seen) == 0 {
		return fmt.Errorf("%s declares no SetConditions method", managedFile)
	}
	types := make([]string, 0, len(seen))
	for t := range seen {
		types = append(types, t)
	}
	sort.Strings(types)

	var b bytes.Buffer
	b.WriteString("// SPDX-FileCopyrightText: 2025 The Crossplane Authors <https://crossplane.io>\n//\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\n")
	b.WriteString("// Code generated by generate-interface-assertions. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", f.Name.Name)
	b.WriteString("import (\n\t\"github.com/crossplane/crossplane-runtime/v2/pkg/resource\"\n)\n\n")
	b.WriteString("// Compile-time assertions that every managed resource in this package satisfies\n")
	b.WriteString("// the crossplane-runtime interfaces the managed reconciler requires. A dropped\n")
	b.WriteString("// angryjet marker or a stale zz_generated.managed.go still compiles cleanly and\n")
	b.WriteString("// would otherwise surface as a runtime panic during reconciliation.\n")
	b.WriteString("var (\n")
	for _, t := range types {
		fmt.Fprintf(&b, "\t_ resource.Managed = &%s{}\n", t)
		if legacy {
			b.WriteString("\t//nolint:staticcheck // LegacyManaged is deprecated in favor of ModernManaged, but cluster-scoped MRs still must satisfy it; this assertion intentionally pins that requirement.\n")
		}
		fmt.Fprintf(&b, "\t_ resource.%s = &%s{}\n", scopeIface, t)
	}
	b.WriteString(")\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("formatting output: %w\n%s", err, b.String())
	}
	return os.WriteFile(filepath.Join(dir, outputFile), src, 0o644)
}
